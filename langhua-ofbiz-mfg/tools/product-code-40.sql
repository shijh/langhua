-- Widens the model code from 20 to 60 characters (the page and the services accept 40).
--
-- Run it with the instance stopped: the embedded Derby locks the database files. Derby refuses to
-- alter a column another table points at, so the seven foreign keys onto MFG_PRODUCT.PRODUCT_CODE
-- are dropped first and added back afterwards. The child columns have to be widened in the same
-- run, otherwise the keys cannot be recreated (a foreign key needs both sides to be the same type).
--
--   java -cp "derby.jar;derbyshared.jar;derbytools.jar" org.apache.derby.tools.ij product-code-40.sql
--   (connect as user=ofbiz: the tables live in the OFBIZ schema)
--
-- The script is written to survive being run twice: a DROP or ALTER that has nothing to do only
-- prints an error and ij moves on, and every step that matters is idempotent.
-- 注意：MFG_ROUTING 上那条外键在库里叫 MFG_ROUTING_PRODUCT（不是实体模型里写的 MFG_ROUTE_PRODUCT），
-- 两个名字都 drop 一次，重跑才能把半途而废的库修回来。

connect 'jdbc:derby:REPLACE_WITH_INSTANCE\runtime\data\derby\ofbiz;user=ofbiz';

-- 1. drop the keys that point at the parent column
ALTER TABLE OFBIZ.MFG_PRODUCT_STAGE_REVIEW DROP CONSTRAINT MFG_PSTG_PRODUCT;
ALTER TABLE OFBIZ.MFG_BOM_ITEM DROP CONSTRAINT MFG_BOM_PRODUCT;
ALTER TABLE OFBIZ.MFG_BOM_VERSION DROP CONSTRAINT MFG_BOMVER_PRODUCT;
ALTER TABLE OFBIZ.MFG_PRODUCT_IMAGE DROP CONSTRAINT MFG_PHOTO_PRODUCT;
ALTER TABLE OFBIZ.MFG_ROUTING DROP CONSTRAINT MFG_ROUTING_PRODUCT;
ALTER TABLE OFBIZ.MFG_ROUTING DROP CONSTRAINT MFG_ROUTE_PRODUCT;
ALTER TABLE OFBIZ.MFG_WORK_ORDER DROP CONSTRAINT MFG_WO_PRODUCT;
ALTER TABLE OFBIZ.MFG_SALES_ORDER_ITEM DROP CONSTRAINT MFG_SOITEM_PRODUCT;

-- 2. widen the parent and every column that holds a model code
ALTER TABLE OFBIZ.MFG_PRODUCT ALTER COLUMN PRODUCT_CODE SET DATA TYPE VARCHAR(60);
ALTER TABLE OFBIZ.MFG_PRODUCT ALTER COLUMN PREVIOUS_PRODUCT_CODE SET DATA TYPE VARCHAR(60);
ALTER TABLE OFBIZ.MFG_PRODUCT_STAGE_REVIEW ALTER COLUMN PRODUCT_CODE SET DATA TYPE VARCHAR(60);
ALTER TABLE OFBIZ.MFG_BOM_ITEM ALTER COLUMN PRODUCT_CODE SET DATA TYPE VARCHAR(60);
ALTER TABLE OFBIZ.MFG_BOM_VERSION ALTER COLUMN PRODUCT_CODE SET DATA TYPE VARCHAR(60);
ALTER TABLE OFBIZ.MFG_PRODUCT_IMAGE ALTER COLUMN PRODUCT_CODE SET DATA TYPE VARCHAR(60);
ALTER TABLE OFBIZ.MFG_ROUTING ALTER COLUMN PRODUCT_CODE SET DATA TYPE VARCHAR(60);
ALTER TABLE OFBIZ.MFG_WORK_ORDER ALTER COLUMN PRODUCT_CODE SET DATA TYPE VARCHAR(60);
ALTER TABLE OFBIZ.MFG_SN ALTER COLUMN PRODUCT_CODE SET DATA TYPE VARCHAR(60);
ALTER TABLE OFBIZ.MFG_DEV_PROJECT ALTER COLUMN PRODUCT_CODE SET DATA TYPE VARCHAR(60);
ALTER TABLE OFBIZ.MFG_DEV_ECO ALTER COLUMN PRODUCT_CODE SET DATA TYPE VARCHAR(60);
ALTER TABLE OFBIZ.MFG_SOFTWARE_PROJECT ALTER COLUMN PRODUCT_CODE SET DATA TYPE VARCHAR(60);
ALTER TABLE OFBIZ.MFG_SALES_ORDER_ITEM ALTER COLUMN PRODUCT_CODE SET DATA TYPE VARCHAR(60);

-- 3. put the keys back
ALTER TABLE OFBIZ.MFG_PRODUCT_STAGE_REVIEW ADD CONSTRAINT MFG_PSTG_PRODUCT FOREIGN KEY (PRODUCT_CODE) REFERENCES OFBIZ.MFG_PRODUCT (PRODUCT_CODE);
ALTER TABLE OFBIZ.MFG_BOM_ITEM ADD CONSTRAINT MFG_BOM_PRODUCT FOREIGN KEY (PRODUCT_CODE) REFERENCES OFBIZ.MFG_PRODUCT (PRODUCT_CODE);
ALTER TABLE OFBIZ.MFG_BOM_VERSION ADD CONSTRAINT MFG_BOMVER_PRODUCT FOREIGN KEY (PRODUCT_CODE) REFERENCES OFBIZ.MFG_PRODUCT (PRODUCT_CODE);
ALTER TABLE OFBIZ.MFG_PRODUCT_IMAGE ADD CONSTRAINT MFG_PHOTO_PRODUCT FOREIGN KEY (PRODUCT_CODE) REFERENCES OFBIZ.MFG_PRODUCT (PRODUCT_CODE);
ALTER TABLE OFBIZ.MFG_ROUTING ADD CONSTRAINT MFG_ROUTE_PRODUCT FOREIGN KEY (PRODUCT_CODE) REFERENCES OFBIZ.MFG_PRODUCT (PRODUCT_CODE);
ALTER TABLE OFBIZ.MFG_WORK_ORDER ADD CONSTRAINT MFG_WO_PRODUCT FOREIGN KEY (PRODUCT_CODE) REFERENCES OFBIZ.MFG_PRODUCT (PRODUCT_CODE);
ALTER TABLE OFBIZ.MFG_SALES_ORDER_ITEM ADD CONSTRAINT MFG_SOITEM_PRODUCT FOREIGN KEY (PRODUCT_CODE) REFERENCES OFBIZ.MFG_PRODUCT (PRODUCT_CODE);

-- 4. what is there now: every model code column 60 wide, seven foreign keys back in place
SELECT t.TABLENAME, c.COLUMNDATATYPE FROM SYS.SYSCOLUMNS c JOIN SYS.SYSTABLES t
    ON c.REFERENCEID = t.TABLEID
    WHERE c.COLUMNNAME = 'PRODUCT_CODE' ORDER BY t.TABLENAME;
SELECT COUNT(*) AS FOREIGN_KEYS FROM SYS.SYSCONSTRAINTS WHERE TYPE = 'F';
SELECT COUNT(*) AS PRODUCTS FROM OFBIZ.MFG_PRODUCT;
SELECT COUNT(*) AS WORK_ORDERS FROM OFBIZ.MFG_WORK_ORDER;
exit;

-- Takes the test data out of a development database and leaves the real work behind.
--
-- Why: every run of the integration test (MfgServiceIT) and of the page verification scripts leaves
-- products, development projects, work orders, lots, receipts and accounts behind. After a few
-- months the development instance was mostly noise: the product development list held 383 projects
-- and none of them was real.
--
-- What it keeps: the development project DEV-261031-04 (the board whose Fritzing BOM was imported by
-- hand, with its twelve outbound documents) and every lot that came from a real purchase. The data
-- of the other verification scripts is left alone: this file takes the development layer and what
-- the integration test made.
--
-- How to run (the instance must be stopped, its embedded Derby locks the database files):
--   java -cp "derby.jar;derbyshared.jar;derbytools.jar" org.apache.derby.tools.ij tools/purge-test-data.sql
-- The connect line below points at the development instance; change the path for another one.
-- Take a copy of runtime\data\derby first. Every delete is by an identifier the test data carries,
-- never by date, so nothing real can be caught by surprise.
--
-- Two things learned the hard way:
--   * children before parents: the entity model has real foreign keys, so the order of the deletes
--     below is not cosmetic;
--   * gather the identifier sets into temporary tables first. Written as IN (SELECT … FROM the big
--     tables) Derby re-runs the subquery for every row it looks at, and one delete ran for more than
--     ten minutes before it was killed. With the sets in SESSION.* tables the whole file runs in
--     about a minute.

connect 'jdbc:derby:F:\build-ofbiz\apache-ofbiz-24.09.07\runtime\data\derby\ofbiz;user=ofbiz';

-- ==================== 0. the sets, gathered once ====================
DECLARE GLOBAL TEMPORARY TABLE SESSION.IT_PROD (CODE VARCHAR(60)) ON COMMIT PRESERVE ROWS NOT LOGGED;
INSERT INTO SESSION.IT_PROD SELECT PRODUCT_CODE FROM OFBIZ.MFG_PRODUCT
    WHERE PRODUCT_CODE LIKE 'IT%' OR PRODUCT_CODE LIKE 'RSVM%' OR PRODUCT_CODE = 'COSTM';
DECLARE GLOBAL TEMPORARY TABLE SESSION.IT_WO (ID VARCHAR(20)) ON COMMIT PRESERVE ROWS NOT LOGGED;
INSERT INTO SESSION.IT_WO SELECT WORK_ORDER_ID FROM OFBIZ.MFG_WORK_ORDER
    WHERE PRODUCT_CODE IN (SELECT CODE FROM SESSION.IT_PROD);
DECLARE GLOBAL TEMPORARY TABLE SESSION.IT_LOT (ID VARCHAR(20)) ON COMMIT PRESERVE ROWS NOT LOGGED;
INSERT INTO SESSION.IT_LOT SELECT LOT_ID FROM OFBIZ.MFG_MATERIAL_LOT
    WHERE COMPONENT_CODE LIKE 'IT%' OR COMPONENT_CODE LIKE 'RSV%' OR COMPONENT_CODE LIKE 'INV%'
       OR COMPONENT_CODE IN ('U1-BT5-SOC','R0402-10K','C0402-100N','BAT-18650','ENC-IT-SHELL','PCB-IT-BT5','IQC-IT-PART','COSTM')
       OR WORK_ORDER_ID IN (SELECT ID FROM SESSION.IT_WO);
DECLARE GLOBAL TEMPORARY TABLE SESSION.IT_SO (ID VARCHAR(20)) ON COMMIT PRESERVE ROWS NOT LOGGED;
INSERT INTO SESSION.IT_SO SELECT SALES_ORDER_ID FROM OFBIZ.MFG_SALES_ORDER
    WHERE CUSTOMER_NAME LIKE 'IT%'
       OR CUSTOMER_NAME IN ('Cost test','Integration test','Reserve test','Outsource test','Finished goods test','Outsource line test');
DECLARE GLOBAL TEMPORARY TABLE SESSION.IT_RCPT (ID VARCHAR(20)) ON COMMIT PRESERVE ROWS NOT LOGGED;
INSERT INTO SESSION.IT_RCPT SELECT RECEIPT_ID FROM OFBIZ.MFG_PURCHASE_RECEIPT
    WHERE SUPPLIER_NAME LIKE 'IT%' OR SUPPLIER_NAME = 'Cost supplier';
DECLARE GLOBAL TEMPORARY TABLE SESSION.IT_DO (ID VARCHAR(20)) ON COMMIT PRESERVE ROWS NOT LOGGED;
INSERT INTO SESSION.IT_DO SELECT DELIVERY_ID FROM OFBIZ.MFG_DELIVERY
    WHERE CUSTOMER_NAME LIKE 'IT%' OR WORK_ORDER_ID IN (SELECT ID FROM SESSION.IT_WO);

-- ==================== 1. the development layer ====================
-- Everything except the real board project. A design BOM, its steps, gates, issues, change orders
-- and outbound orders belong to one project and mean nothing without it.
DELETE FROM OFBIZ.MFG_DEV_BOM_ITEM WHERE PROJECT_CODE <> 'DEV-261031-04';
DELETE FROM OFBIZ.MFG_DEV_BOM WHERE PROJECT_CODE <> 'DEV-261031-04';
DELETE FROM OFBIZ.MFG_OUTBOUND_ITEM WHERE OUTBOUND_ID IN
    (SELECT OUTBOUND_ID FROM OFBIZ.MFG_OUTBOUND WHERE PROJECT_CODE <> 'DEV-261031-04');
DELETE FROM OFBIZ.MFG_OUTBOUND WHERE PROJECT_CODE <> 'DEV-261031-04';
DELETE FROM OFBIZ.MFG_DEV_TRACK_STEP WHERE PROJECT_CODE <> 'DEV-261031-04';
DELETE FROM OFBIZ.MFG_DEV_STAGE_REVIEW WHERE PROJECT_CODE <> 'DEV-261031-04';
DELETE FROM OFBIZ.MFG_DEV_STEP_ISSUE WHERE PROJECT_CODE <> 'DEV-261031-04';
DELETE FROM OFBIZ.MFG_DEV_ECO WHERE PROJECT_CODE IS NOT NULL AND PROJECT_CODE <> 'DEV-261031-04';
DELETE FROM OFBIZ.MFG_SOFTWARE_PROJECT WHERE DEV_PROJECT_CODE IS NOT NULL AND DEV_PROJECT_CODE <> 'DEV-261031-04';
DELETE FROM OFBIZ.MFG_DEV_PROJECT WHERE PROJECT_CODE <> 'DEV-261031-04';
-- The locks those projects held on the shelf: without the project nobody could release them, and a
-- stale reservation keeps the part out of every work order for good.
DELETE FROM OFBIZ.MFG_INVENTORY_DETAIL WHERE DEV_PROJECT_CODE IS NOT NULL AND DEV_PROJECT_CODE <> 'DEV-261031-04';

-- ==================== 2. what the integration test made ====================
DELETE FROM OFBIZ.MFG_REPLACEMENT WHERE SN LIKE 'ITMFG-%' OR WORK_ORDER_ID IN (SELECT ID FROM SESSION.IT_WO);
DELETE FROM OFBIZ.MFG_WARRANTY_CLAIM WHERE SN LIKE 'ITMFG-%' OR WORK_ORDER_ID IN (SELECT ID FROM SESSION.IT_WO);
DELETE FROM OFBIZ.MFG_DELIVERY_SN WHERE SN LIKE 'ITMFG-%' OR DELIVERY_ID IN (SELECT ID FROM SESSION.IT_DO);
DELETE FROM OFBIZ.MFG_DELIVERY WHERE DELIVERY_ID IN (SELECT ID FROM SESSION.IT_DO);
DELETE FROM OFBIZ.MFG_TEST_RESULT WHERE SN LIKE 'ITMFG-%' OR WORK_ORDER_ID IN (SELECT ID FROM SESSION.IT_WO);
DELETE FROM OFBIZ.MFG_DEFECT WHERE WORK_ORDER_ID IN (SELECT ID FROM SESSION.IT_WO);
DELETE FROM OFBIZ.MFG_REPORT WHERE WORK_ORDER_ID IN (SELECT ID FROM SESSION.IT_WO);
DELETE FROM OFBIZ.MFG_SN WHERE SN LIKE 'ITMFG-%' OR WORK_ORDER_ID IN (SELECT ID FROM SESSION.IT_WO);
DELETE FROM OFBIZ.MFG_OUTSOURCE_FEE WHERE WORK_ORDER_ID IN (SELECT ID FROM SESSION.IT_WO);
DELETE FROM OFBIZ.MFG_SHIPMENT WHERE WORK_ORDER_ID IN (SELECT ID FROM SESSION.IT_WO);
DELETE FROM OFBIZ.MFG_MATERIAL_ISSUE WHERE WORK_ORDER_ID IN (SELECT ID FROM SESSION.IT_WO) OR LOT_ID IN (SELECT ID FROM SESSION.IT_LOT);
DELETE FROM OFBIZ.MFG_INVENTORY_DETAIL WHERE WORK_ORDER_ID IN (SELECT ID FROM SESSION.IT_WO) OR LOT_ID IN (SELECT ID FROM SESSION.IT_LOT);
DELETE FROM OFBIZ.MFG_STOCK_COUNT WHERE LOT_ID IN (SELECT ID FROM SESSION.IT_LOT);
DELETE FROM OFBIZ.MFG_PURCHASE_RECEIPT_LINE WHERE LOT_ID IN (SELECT ID FROM SESSION.IT_LOT) OR RECEIPT_ID IN (SELECT ID FROM SESSION.IT_RCPT);
DELETE FROM OFBIZ.MFG_SALES_ORDER_ITEM WHERE PRODUCT_CODE IN (SELECT CODE FROM SESSION.IT_PROD) OR SALES_ORDER_ID IN (SELECT ID FROM SESSION.IT_SO);
DELETE FROM OFBIZ.MFG_SALES_ORDER WHERE SALES_ORDER_ID IN (SELECT ID FROM SESSION.IT_SO);
DELETE FROM OFBIZ.MFG_PURCHASE_RECEIPT WHERE RECEIPT_ID IN (SELECT ID FROM SESSION.IT_RCPT);
DELETE FROM OFBIZ.MFG_MATERIAL_LOT WHERE LOT_ID IN (SELECT ID FROM SESSION.IT_LOT);
DELETE FROM OFBIZ.MFG_BOM_VERSION_ITEM WHERE BOM_VERSION_ID IN
    (SELECT BOM_VERSION_ID FROM OFBIZ.MFG_BOM_VERSION WHERE PRODUCT_CODE IN (SELECT CODE FROM SESSION.IT_PROD));
DELETE FROM OFBIZ.MFG_BOM_VERSION WHERE PRODUCT_CODE IN (SELECT CODE FROM SESSION.IT_PROD);
DELETE FROM OFBIZ.MFG_BOM_ITEM WHERE PRODUCT_CODE IN (SELECT CODE FROM SESSION.IT_PROD);
DELETE FROM OFBIZ.MFG_ROUTING WHERE PRODUCT_CODE IN (SELECT CODE FROM SESSION.IT_PROD);
DELETE FROM OFBIZ.MFG_PRODUCT_IMAGE WHERE PRODUCT_CODE IN (SELECT CODE FROM SESSION.IT_PROD);
DELETE FROM OFBIZ.MFG_DEV_ECO WHERE PRODUCT_CODE IN (SELECT CODE FROM SESSION.IT_PROD);
DELETE FROM OFBIZ.MFG_STOCK_SETTING WHERE COMPONENT_CODE LIKE 'IT%' OR COMPONENT_CODE LIKE 'RSV%' OR COMPONENT_CODE LIKE 'INV%'
    OR COMPONENT_CODE IN ('U1-BT5-SOC','R0402-10K','C0402-100N','BAT-18650','ENC-IT-SHELL','PCB-IT-BT5','IQC-IT-PART');
DELETE FROM OFBIZ.MFG_WORK_ORDER WHERE WORK_ORDER_ID IN (SELECT ID FROM SESSION.IT_WO);
DELETE FROM OFBIZ.MFG_ATTACHMENT WHERE OWNER_TYPE_ID = 'PRODUCT' AND OWNER_ID IN (SELECT CODE FROM SESSION.IT_PROD);
DELETE FROM OFBIZ.MFG_PRODUCT WHERE PRODUCT_CODE IN (SELECT CODE FROM SESSION.IT_PROD);

-- ==================== 3. the small masters it made ====================
DELETE FROM OFBIZ.MFG_VENDOR WHERE VENDOR_NAME LIKE 'IT %';
DELETE FROM OFBIZ.MFG_BUYER_FLAG WHERE BUYER_NICK = 'it_buyer';
DELETE FROM OFBIZ.MFG_STOCK_LOCATION WHERE LOCATION_ID LIKE 'IT-%';
DELETE FROM OFBIZ.MFG_SOFTWARE_PROJECT WHERE PROJECT_NAME LIKE 'IT %';
-- Its throw-away accounts (ituHHmmss). OFBiz keeps references to a user login, so they are disabled
-- rather than deleted and their security groups are dropped (AGENTS.md, "生产只留一个 admin").
DELETE FROM OFBIZ.USER_LOGIN_SECURITY_GROUP WHERE USER_LOGIN_ID LIKE 'itu%';
UPDATE OFBIZ.USER_LOGIN SET ENABLED = 'N' WHERE USER_LOGIN_ID LIKE 'itu%';

-- ==================== 4. the shelf totals again ====================
-- Two of the deletes above took movements away (the locks of the deleted projects, the lots of the
-- test data), so every remaining lot is summed again from what is left: the same formula the
-- application uses in MfgStockLedger.recalcLotStock.
UPDATE OFBIZ.MFG_MATERIAL_LOT SET ON_HAND_QTY =
    (SELECT COALESCE(SUM(D.QUANTITY_DIFF), 0) FROM OFBIZ.MFG_INVENTORY_DETAIL D WHERE D.LOT_ID = OFBIZ.MFG_MATERIAL_LOT.LOT_ID);
UPDATE OFBIZ.MFG_MATERIAL_LOT SET RESERVED_QTY =
    (SELECT COALESCE(SUM(D.RESERVED_DIFF), 0) FROM OFBIZ.MFG_INVENTORY_DETAIL D WHERE D.LOT_ID = OFBIZ.MFG_MATERIAL_LOT.LOT_ID);
UPDATE OFBIZ.MFG_MATERIAL_LOT SET RESERVED_QTY = 0 WHERE RESERVED_QTY < 0;
UPDATE OFBIZ.MFG_MATERIAL_LOT SET AVAILABLE_QTY = CASE
    WHEN INSPECT_STATUS_ID = 'MFG_IQC_FAIL' THEN 0
    WHEN ON_HAND_QTY - RESERVED_QTY < 0 THEN 0
    ELSE ON_HAND_QTY - RESERVED_QTY END;

-- ==================== 5. what is left ====================
SELECT COUNT(*) AS DEV_PROJECTS FROM OFBIZ.MFG_DEV_PROJECT;
SELECT COUNT(*) AS PRODUCTS FROM OFBIZ.MFG_PRODUCT;
SELECT COUNT(*) AS WORK_ORDERS FROM OFBIZ.MFG_WORK_ORDER;
SELECT COUNT(*) AS LOTS FROM OFBIZ.MFG_MATERIAL_LOT;
SELECT COUNT(*) AS MOVEMENTS FROM OFBIZ.MFG_INVENTORY_DETAIL;
SELECT COUNT(*) AS RECEIPTS FROM OFBIZ.MFG_PURCHASE_RECEIPT;
SELECT COUNT(*) AS OUTBOUNDS FROM OFBIZ.MFG_OUTBOUND;
SELECT COUNT(*) AS ENABLED_ACCOUNTS FROM OFBIZ.USER_LOGIN WHERE ENABLED = 'Y';
exit;
